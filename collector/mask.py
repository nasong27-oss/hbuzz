"""리포트 표시용 비속어 마스킹. 매칭된 비속어를 ■(검정 사각형)로 가린다(길이 보존).
원본(archive)엔 적용하지 않고, 리포트에 나가는 텍스트(제목·요약·사유)에만 적용한다.
늘려쓰기(씨이발)·초성(ㅅㅂ)·변형을 정규식으로 폭넓게 잡는다."""
import re

# 변형/늘려쓰기 허용 정규식 계열 (강한 욕설)
_PATTERNS = [
    r"씨+[이으야아]*[발벌빨불붕]",     # 씨발 씨이발 씨이이발 씨벌 씨빨
    r"시+[이으야아]*[발벌빨팔]",       # 시발 시이발 시벌 시팔
    r"쓰+[이으]*[발벌빨]",             # 쓰발
    r"ㅅ+ㅂ+|ㅆ+ㅂ+|ㅈ+ㄹ+|ㅂ+ㅅ+",   # 초성 ㅅㅂ ㅈㄹ ㅂㅅ
    r"개*[새쉐쌔]+[끼키]+",            # 새끼 개새끼 개쉐끼 새키
    r"존+[나내니너]+",                 # 존나 존내
    r"ㅈ+같|좆+[같도밥나]*|좇+",        # 좆같 좆도 좆밥
    r"병+[신싄쉰]+|븅+신|빙+신",       # 병신 븅신 빙신
    r"지+[랄럴]+",                     # 지랄 지럴
    r"허+벌+[나]*",                    # 허벌 허벌나
    r"씹+[새년창할스빠]*",             # 씹 씹새 씹년 씹창
    r"엠+창|니+[애에]+미|느+[금검]+마?|[애에]+미+없",  # 엠창 니애미 느금마 애미없
    r"[시씨]+부+[랄럴]+",              # 시부랄 씨부랄
    r"좆+manle?",                      # (영타 혼용 방어용, 거의 안 씀)
]

# 단순 단어(변형 적은 것)
_WORDS = [
    "썅", "썅놈", "썅년", "개소리", "개같", "개빡", "등신", "걸레", "창녀",
    "닥쳐", "꺼져라", "엿먹", "개지랄", "썩을",
]
_WORDS = sorted(set(_WORDS), key=len, reverse=True)

_COMBINED = re.compile("|".join(_PATTERNS + [re.escape(w) for w in _WORDS]))


def mask_profanity(text):
    """비속어를 같은 길이의 ■ 로 치환. text 없으면 그대로 반환."""
    if not text:
        return text
    return _COMBINED.sub(lambda m: "■" * len(m.group(0)), text)
